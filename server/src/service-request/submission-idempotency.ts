import { checksum } from '../attachments/attachment.domain.js';
import { requestUuid } from './staff-request-scope.js';

/**
 * F066 submission idempotency: the pure decisions.
 *
 * Nothing here touches a database, a clock it was not given, or a request. The
 * classification that decides whether a submission is new, a replay or a
 * refusal is a function of recorded state and a supplied instant, so every
 * branch is provable against fabricated input.
 */

/**
 * The retry window for a recorded submission.
 *
 * Long enough to cover a lost response, an offline queue drain and a user who
 * retries after a timeout; short enough that a key is not a permanent
 * reservation. Past this horizon the key is refused rather than being allowed
 * to create a second request that the client would read as an exact replay --
 * a silent duplicate is the exact failure this feature exists to prevent, and
 * a stale key producing one would be worse than an honest refusal.
 */
export const SUBMISSION_RETENTION_MINIMUM_HOURS = 1;
export const SUBMISSION_RETENTION_DEFAULT_HOURS = 24;
export const SUBMISSION_RETENTION_MAXIMUM_HOURS = 168;

/**
 * Bounds the retry window the way F065 bounds a credential lifetime: the
 * platform maximum holds even if a future configuration surface supplies
 * something outside it, and an absent or non-integer value takes the default
 * rather than being guessed at.
 */
export function submissionRetentionHours(value: unknown): number {
  if (typeof value !== 'number' || !Number.isInteger(value))
    return SUBMISSION_RETENTION_DEFAULT_HOURS;
  return Math.min(
    Math.max(value, SUBMISSION_RETENTION_MINIMUM_HOURS),
    SUBMISSION_RETENTION_MAXIMUM_HOURS,
  );
}

/**
 * The accepted key shape, matching the `Idempotency-Key` contract the note and
 * communication paths already use: a UUID, which carries 122 random bits when
 * generated by a version 4 generator.
 *
 * Shape and length are validated rather than trusted. A short or structured
 * key would make the reservation space guessable, and the refusal distinguishes
 * "you sent nothing usable" from "this key is already spoken for".
 */
export function validSubmissionKey(value: unknown): value is string {
  return typeof value === 'string' && requestUuid.test(value);
}

/**
 * Only the digest is ever persisted. The raw key stays in the request that
 * carried it, so a disclosed database backup cannot be replayed against the
 * submission endpoint, and the stored value has a fixed shape regardless of
 * what the client sent.
 */
export function submissionKeyDigest(key: string): string {
  return checksum(`reqro.f066.submission-key\u0000${key}`);
}

/**
 * The authorized submission context a key is scoped to, derived entirely from
 * server-resolved values.
 *
 * A staff submission is bound to the acting staff identity, so one staff
 * member's key can neither collide with nor replay another's. Resident PUBLIC
 * intake is anonymous by design and has no identity to bind, so its scope is
 * the channel alone; the fingerprint binding below is what prevents a key
 * collision from returning someone else's receipt.
 *
 * The Organization is deliberately *not* part of this string. It is a separate
 * column and a separate foreign key, so tenant scoping cannot be weakened by a
 * formatting mistake here, and no client-supplied value reaches either.
 */
export function submissionScope(context: {
  audience: 'public' | 'internal';
  intakeChannel: string;
  staffId: string | null;
}): string {
  const channel = /^[a-z_]{1,24}$/.test(context.intakeChannel)
    ? context.intakeChannel
    : 'unknown';
  return context.staffId
    ? `${context.audience}:${channel}:staff:${context.staffId}`
    : `${context.audience}:${channel}`;
}

/**
 * The canonical submission fingerprint.
 *
 * Built on the digest the creation path already computes for attachment
 * binding, so one canonical shape serves both mechanisms and they cannot drift
 * apart. The attachment batch's identity is folded in because a retry that
 * carries a different batch is not the same submission: without this, the same
 * key with a replaced batch would return the first receipt and silently
 * discard the new evidence.
 *
 * The batch *token* is excluded. It is a bearer value, and a bearer value does
 * not belong in a stored digest even a one-way one -- `batchId` identifies the
 * batch without it.
 */
export function submissionFingerprint(
  submissionDigest: string,
  attachments?: { batchId: string },
): string {
  return checksum(
    JSON.stringify({
      version: 1,
      submission: submissionDigest,
      attachmentBatchId: attachments?.batchId ?? null,
    }),
  );
}

/**
 * The refusal codes a client may act on.
 *
 * These are admitted through the error filter's allowlist, so unlike a bare
 * conflict they reach the browser with a message. That matters for behavior,
 * not just wording: an unrecognised 409 from this endpoint is treated by the
 * resident client as a stale catalog version and discards the submission the
 * user just made. A retryable conflict must be distinguishable from that.
 *
 * Each code tells the caller only about a key the caller itself supplied. An
 * attacker who guessed a key would learn that it is in use, which is the
 * unavoidable cost of any idempotency contract and is not enumerable against
 * a 122-bit random key. None of them reveals a reference number, a request
 * identity, a tenant or whether any particular request exists.
 */
export const SUBMISSION_KEY_REUSED = 'SUBMISSION_KEY_REUSED';
export const SUBMISSION_RETRY_WINDOW_CLOSED = 'SUBMISSION_RETRY_WINDOW_CLOSED';
export const SUBMISSION_IN_PROGRESS = 'SUBMISSION_IN_PROGRESS';

/** What a recorded reservation means for the submission now being handled. */
export type SubmissionOutcome =
  | { kind: 'first' }
  | { kind: 'replay'; serviceRequestId: string; trackingIssued: boolean }
  | { kind: 'mismatch' }
  | { kind: 'expired' }
  | { kind: 'in_progress' };

export interface SubmissionReservation {
  readonly fingerprint: string;
  readonly service_request_id: string;
  /**
   * Whether the original submission minted an F065 credential.
   *
   * `unknown` because it arrives from a database row rather than from code:
   * only an explicit `true` is read as "a credential exists", so an
   * unexpected value reports no link instead of promising one that cannot be
   * produced.
   */
  readonly tracking_issued: unknown;
  /**
   * Whether the retry window has closed, as evaluated by the **database**
   * clock against the stored `expires_at`.
   *
   * Deliberately not a timestamp compared here. F065 evaluates credential
   * expiry in SQL for the same reason: an application clock that is skewed,
   * or that a caller could influence, must not be able to extend a window
   * the database recorded. Only an explicit `false` -- a positive answer that
   * the window is still open -- permits a replay.
   *
   * `unknown` for the same reason as `tracking_issued`: it is row data, so the
   * comparison below is a genuine trust boundary and not a redundant check on
   * a value the type system already guarantees.
   */
  readonly expired: unknown;
}

/**
 * Pure. Classifies a recorded reservation against the submission in hand.
 *
 * `undefined` means the key was free, which is the only path that creates
 * anything. Every other branch is either a safe replay of the original request
 * or a refusal; none of them creates a second request, a second credential or
 * a second audit event.
 *
 * A fingerprint mismatch is tested before expiry. Both refuse, but a key
 * presented with a different payload is a misuse signal that should be
 * reported as such whatever the record's age, rather than being masked by the
 * window having closed.
 *
 * Anything other than a positive "still open" is treated as expired. A record
 * that cannot be shown to be inside its retry window, or whose request
 * identity is malformed, fails closed rather than being replayed.
 */
export function classifySubmission(
  recorded: SubmissionReservation | undefined,
  fingerprint: string,
): SubmissionOutcome {
  if (recorded === undefined) return { kind: 'first' };
  if (recorded.fingerprint !== fingerprint) return { kind: 'mismatch' };
  if (recorded.expired !== false) return { kind: 'expired' };
  if (!validRequestId(recorded.service_request_id)) return { kind: 'expired' };
  return {
    kind: 'replay',
    serviceRequestId: recorded.service_request_id,
    trackingIssued: recorded.tracking_issued === true,
  };
}

/**
 * A recorded request identity must still look like one before it is used to
 * read a request back. The deferred foreign key means a committed row always
 * names a real request, so this guards against a malformed row rather than a
 * missing one, and refuses instead of querying with it.
 */
export function validRequestId(value: unknown): value is string {
  return typeof value === 'string' && requestUuid.test(value);
}

/**
 * How a replay reports the F065 tracking link.
 *
 * `issued_unrecoverable` is the honest answer to the lost-response problem:
 * the original submission minted a credential, only its digest was stored, and
 * no amount of replaying can return the raw value. Reporting it as anything
 * softer would represent safe request replay as tracking-link recovery, which
 * it is not.
 */
export type ReplayTrackingState = 'issued_unrecoverable' | 'not_issued';

export function replayTrackingState(
  trackingIssued: boolean,
): ReplayTrackingState {
  return trackingIssued ? 'issued_unrecoverable' : 'not_issued';
}
